const fs = require('node:fs/promises');
const path = require('node:path');

const REPO_OWNER = 'kavispires';
const REPO_NAME = 'td-resources';
const TARGET_DIR = 'resources';
const API_URL = `https://api.github.com/repos/${REPO_OWNER}/${REPO_NAME}/contents/${TARGET_DIR}`;

// Helper to format keys like "arte-ruim-cards" into "ARTE_RUIM_CARDS"
const toScreamingSnake = (str) => str.replace(/-/g, '_').toUpperCase();

async function syncResources() {
  try {
    console.log(`Fetching file list from ${API_URL}...`);
    const response = await fetch(API_URL);

    if (!response.ok) {
      throw new Error(`GitHub API responded with status ${response.status}: ${response.statusText}`);
    }

    const data = await response.json();

    // 1. Filter out non-json, remove the .json extension, and sort
    const allRawFiles = data
      .filter(item => item.type === 'file' && item.name.endsWith('.json'))
      .map(item => item.name.replace('.json', ''))
      .sort();

    console.log(`Found ${allRawFiles.length} JSON files.`);

    const uniqueBaseNames = new Set();
    const singleLangBaseNames = new Set();
    const dualLangBaseNames = new Set();

    // 2. Parse language suffixes and categorize
    allRawFiles.forEach(name => {
      if (name.endsWith('-en') || name.endsWith('-pt')) {
        const base = name.replace(/-en$|-pt$/, '');
        uniqueBaseNames.add(base);
        singleLangBaseNames.add(base);
      } else {
        uniqueBaseNames.add(name);
        dualLangBaseNames.add(name);
      }
    });

    const sortedBaseNames = Array.from(uniqueBaseNames).sort();

    // 3. Build the TypeScript file content
    let fileContent = `// This file is auto-generated by scripts/sync-resources.cjs\n// Do not edit this file manually.\n\n`;

    // Write ALL_RESOURCES_LIST (independent raw strings with suffixes if any)
    fileContent += `export const ALL_RESOURCES_LIST = [\n`;
    allRawFiles.forEach(name => {
      fileContent += `  '${name}',\n`;
    });
    fileContent += `] as const;\n\n`;

    // Write RESOURCES_NAMES (base names, no suffixes)
    fileContent += `export const RESOURCES_NAMES = {\n`;
    sortedBaseNames.forEach(base => {
      fileContent += `  ${toScreamingSnake(base)}: '${base}',\n`;
    });
    fileContent += `} as const;\n\n`;

    // Write DUAL_LANGUAGE_RESOURCES
    fileContent += `export const DUAL_LANGUAGE_RESOURCES = [\n`;
    Array.from(dualLangBaseNames).sort().forEach(base => {
      fileContent += `  RESOURCES_NAMES.${toScreamingSnake(base)},\n`;
    });
    fileContent += `] as const;\n\n`;

    // Write SINGLE_LANGUAGE_RESOURCES
    fileContent += `export const SINGLE_LANGUAGE_RESOURCES = [\n`;
    Array.from(singleLangBaseNames).sort().forEach(base => {
      fileContent += `  RESOURCES_NAMES.${toScreamingSnake(base)},\n`;
    });
    fileContent += `] as const;\n`;

    // 4. Output the file
    const outputDir = path.join(process.cwd(), 'src', 'utils');
    const outputFile = path.join(outputDir, 'resources-list.ts');

    await fs.mkdir(outputDir, { recursive: true });
    await fs.writeFile(outputFile, fileContent, 'utf-8');

    console.log(`✅ Successfully wrote resource list to ${outputFile}`);
  } catch (error) {
    console.error('❌ Error fetching resource list:', error);
    process.exit(1);
  }
}

syncResources();
